// Extracts Fig 9.1 (the research time trial) from the HACK Lab field guide into one standalone
// page, public/lab/research-track.html, which the Lab page embeds in an iframe.
//
//   node scripts/lab-figure/embed.mjs [path/to/hack-lab]      (default: ../hack-lab)
//
// The field guide is the public, alias-only edition of the Lab's documentation (hack-lab
// docs/website). Rebuild it there first (`node docs/website/src/build.mjs --only research`), then
// run this. The page keeps the figure, its scene buttons, its side panel and its scripts, set in
// the light theme with this site's own fonts, and tells the parent page its height.
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const lab = resolve(process.argv[2] ?? "../hack-lab");
const site = join(lab, "docs", "website");
const html = readFileSync(join(site, "research.html"), "utf8");

function block(start) {
  let depth = 0;
  const re = /<(\/?)div\b[^>]*>/g;
  re.lastIndex = start;
  for (let m; (m = re.exec(html)); ) {
    depth += m[1] ? -1 : 1;
    if (depth === 0) return html.slice(start, re.lastIndex);
  }
  throw new Error("unbalanced figure block");
}
const at = html.indexOf('<div class="fig" id="jb">');
if (at < 0) throw new Error("Fig 9.1 not found in research.html");
const fig = block(at);

const glossary = (html.match(/<script>window\.GLOSSARY=[\s\S]*?<\/script>/) || [""])[0];
const modules = html.match(/<script type="module">[\s\S]*?<\/script>/g) || [];
if (!modules.length) throw new Error("the figure's module script was not found");
const css = readFileSync(join(site, "assets", "site.css"), "utf8");
// The figure's own styles sit in the page body, before its module script.
const firstModule = html.indexOf('<script type="module">');
const pageStyles = (html.slice(0, firstModule).match(/<style[^>]*>[\s\S]*?<\/style>/g) || []).join("\n");
const js = readFileSync(join(site, "assets", "site.js"), "utf8");

const fonts = `
@font-face { font-family: "Inter Tight"; src: url("/fonts/inter-tight-latin-wght-normal.woff2") format("woff2"); font-weight: 100 900; font-display: swap; }
@font-face { font-family: "Inter"; src: url("/fonts/inter-latin-wght-normal.woff2") format("woff2"); font-weight: 100 900; font-display: swap; }
@font-face { font-family: "IBM Plex Mono"; src: url("/fonts/ibm-plex-mono-latin-500-normal.woff2") format("woff2"); font-weight: 400 500; font-display: swap; }`;
const embed = `
body { background: transparent; overflow: hidden; }
.fig { margin: 0 auto; }
.fig .iso-caption { display: none; } /* the Lab page captions the drawing itself */`;
const height = `<script>(function(){var fig=document.querySelector(".fig");function post(){parent.postMessage({hitlFigure:"research-track",height:Math.ceil(fig.getBoundingClientRect().bottom+window.scrollY+8)},"*")}addEventListener("load",post);addEventListener("message",function(e){if(e.data&&e.data.hitlFigure==="ping")post()});new ResizeObserver(post).observe(fig)})()</script>`;

const page = `<!doctype html>
<!-- Generated by scripts/lab-figure/embed.mjs from the HACK Lab field guide (hack-lab docs/website, Fig 9.1). Do not edit. -->
<html lang="en" class="iso" data-theme="light">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>The research time trial · Hackers in the Loop Lab</title>
<style>${fonts}
${css}
${embed}</style>
</head>
<body data-page="research">
${fig}
<div class="pop" role="tooltip" hidden><p class="pop-t"></p><p class="pop-b"></p></div>
${pageStyles}
${glossary}
<script>${js.replace(/<\/(script)/gi, "<\\/$1")}</script>
${modules.join("\n")}
${height}
</body>
</html>
`;
writeFileSync("public/lab/research-track.html", page);
console.log(`public/lab/research-track.html  ${(page.length / 1024).toFixed(0)} KB`);
